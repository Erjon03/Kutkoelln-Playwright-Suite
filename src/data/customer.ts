import type { ResolvedConfig, CustomerAddress } from '../config/types';

export interface TestCustomer {
  email: string;
  password: string;
  firstName: string;
  lastName: string;
  salutationIndex: number;
  address: CustomerAddress;
  /** B2B registration only */
  company?: string;
  vatId?: string;
}

/**
 * Upper limit for creating a customer (Admin API, Store API or registration form). Some shops send several
 * e-mails while the customer is saved, which can take minutes on a slow mail server.
 */
export const CUSTOMER_CREATE_TIMEOUT = 180_000;

/**
 * Test identity per flow. Everything the suite creates (customers, addresses, contact messages, guest orders)
 * uses the profile's first name + the flow's last name, and an e-mail
 *   <emailPrefix>-<flow>-<unique>@<emailDomain>
 * so shop staff can see at a glance which test created a record. Specs never hardcode names — they pick a flow.
 */
export const FLOWS = {
  /** the worker's shared customer (login, account, cart, wishlist, checkout tests) */
  customer: 'Customer',
  /** own customer for tests that change password / e-mail */
  loginData: 'LoginData',
  /** new address of the e-mail change test */
  emailChange: 'EmailChange',
  registration: 'Registration',
  registrationInvalid: 'RegistrationInvalid',
  passwordMismatch: 'PasswordMismatch',
  guestCheckout: 'GuestCheckout',
  profileChange: 'ProfileChanged',
  addressAdd: 'AddressAdded',
  addressEdit: 'AddressEdited',
  contact: 'ContactForm',
  contactInvalid: 'ContactInvalidEmail',
  /** login attempt with an address that is never registered */
  unknownUser: 'UnknownUser',
} as const;

export type Flow = keyof typeof FLOWS;

const rand = () => Math.random().toString(36).slice(2, 8);

/** Unique e-mail per call: <prefix>-<flow>-<timestamp><rand>@<domain> — easy to clean up by prefix. */
export function uniqueEmail(cfg: ResolvedConfig, flow: Flow = 'customer'): string {
  const { emailPrefix, emailDomain } = cfg.testData.customer;
  return `${emailPrefix}-${flow.toLowerCase()}-${Date.now()}${rand()}@${emailDomain}`;
}

/**
 * Matches only e-mails generated by uniqueEmail() — never a manually created account that merely starts
 * with the same prefix (e.g. <prefix>-manual@<domain>). Used by the cleanup.
 */
export function generatedEmailPattern(emailPrefix: string, emailDomain: string): RegExp {
  const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`^${esc(emailPrefix.toLowerCase())}-[a-z]+-\\d{13}[a-z0-9]{1,6}@${esc(emailDomain.toLowerCase())}$`);
}

/** Last name of the test identity for a flow. */
export function flowLastName(flow: Flow): string {
  return FLOWS[flow];
}

export function buildCustomer(cfg: ResolvedConfig, flow: Flow = 'customer', overrides: Partial<TestCustomer> = {}): TestCustomer {
  const c = cfg.testData.customer;
  return {
    email: uniqueEmail(cfg, flow),
    password: c.password,
    firstName: c.firstName,
    lastName: flowLastName(flow),
    salutationIndex: c.salutationIndex,
    address: { ...c.address },
    company: c.company,
    vatId: c.vatId,
    ...overrides,
  };
}
